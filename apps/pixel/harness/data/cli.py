"""python -m harness data {list | collect | status | derive | plan | label}"""
from __future__ import annotations

import json
from pathlib import Path

from . import data_root
from .apis import expand
from .collect import Collector
from .manifest import TIERS, by_id, load_manifest


def _select(sources, ids, tier_max, access=None):
    rank = {t: i for i, t in enumerate(TIERS)}
    out = []
    for s in sources:
        if ids and s.id not in ids:
            continue
        if not ids and rank[s.tier] > rank[tier_max]:
            continue
        if access and s.access not in access:
            continue
        out.append(s)
    return out


def cmd_list(args) -> int:
    sources = load_manifest()
    st = Collector(log=lambda *_: None).status() if data_root().exists() else {}
    sel = _select(sources, args.ids, args.tier, args.access)
    print(f"{'id':34} {'tier':4} {'access':10} {'size':>8}  {'have':>12}  use")
    for s in sel:
        have = st.get(s.id)
        have_s = f"{have['files']}f/{have['bytes'] / 1e6:.0f}MB" if have else "-"
        print(f"{s.id:34} {s.tier:4} {s.access:10} {s.size_bytes / 1e6:7.0f}M  {have_s:>12}  {s.harness_use[:60]}")
    print(f"{len(sel)} source(s); data root {data_root()}")
    return 0


def cmd_collect(args) -> int:
    sources = by_id(load_manifest())
    sel = _select(list(sources.values()), args.ids, args.tier)
    overrides = dict(kv.split("=", 1) for kv in (args.param or []))
    c = Collector(jobs=args.jobs, dry_run=args.dry_run, max_bytes=args.max_bytes)
    results, skipped = [], []
    for s in sel:
        if not s.fetchable:
            skipped.append(f"{s.id} ({s.access})")
            continue
        s.params.update(overrides)
        try:
            specs = expand(c, s)
        except Exception as ex:  # noqa: BLE001
            print(f"{s.id}: expand failed: {type(ex).__name__}: {ex}")
            c.note_expand(s, ex)
            results.append({"source": s.id, "failed": 1, "errors": [str(ex)]})
            continue
        c.note_expand(s)
        results.append(c.fetch_source(s, specs))
    if skipped:
        print("not fetchable here (manual / pip / docker / page-only): " + ", ".join(skipped))
    (data_root() / "last_collect.json").parent.mkdir(parents=True, exist_ok=True)
    if not args.dry_run:
        (data_root() / "last_collect.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    failed = sum(r.get("failed", 0) for r in results)
    return 1 if failed else 0


def cmd_status(args) -> int:
    c = Collector(log=lambda *_: None)
    st = c.status()
    tot_f = sum(v["files"] for v in st.values())
    tot_b = sum(v["bytes"] for v in st.values())
    for k, v in sorted(st.items()):
        fail = f"   {v['failed']} failed: {v['error'][:70]}" if v.get("failed") else ""
        print(f"{k:34} {v['files']:7d} files {v['bytes'] / 1e6:10.1f} MB{fail}")
    print(f"{'total':34} {tot_f:7d} files {tot_b / 1e6:10.1f} MB   ({c.ledger_path})")
    return 0


def cmd_derive(args) -> int:
    from .derive import run_derivers
    report = run_derivers(args.ids)
    for k, v in report.items():
        print(f"{k:34} {v}")
    return 0


PLAN_BEGIN, PLAN_END = "<!-- plan:begin (generated by `python -m harness data plan`) -->", "<!-- plan:end -->"


def render_plan() -> str:
    """Markdown: every source with tier, access, licence, size, what it feeds and what is on disk.
    Derived from the manifest + ledger + catalogue, so it never drifts from them."""
    from collections import Counter
    sources = load_manifest()
    st = Collector(log=lambda *_: None).status() if data_root().exists() else {}
    cat_path = Path(__file__).with_name("catalog") / "datasets.json"
    cat = json.loads(cat_path.read_text(encoding="utf-8"))["datasets"] if cat_path.exists() else []
    covered = {n.split("catalog:", 1)[1].split(".", 1)[0] for s in sources for n in [s.notes] if "catalog:" in n}
    lines = []
    by_tier = Counter(s.tier for s in sources)
    fetch_b = sum(s.size_bytes for s in sources if s.fetchable)
    have_b = sum(v["bytes"] for v in st.values())
    have_f = sum(v["files"] for v in st.values())
    lines.append(f"**{len(sources)} sources** ({', '.join(f'{t}: {by_tier[t]}' for t in TIERS)}); "
                 f"fetchable from here: {sum(s.fetchable for s in sources)}, planned bytes {fetch_b / 1e9:,.1f} GB; "
                 f"on disk: {have_f} files, {have_b / 1e9:.2f} GB across {sum(1 for v in st.values() if v['files'])} sources; "
                 f"{sum(v['failed'] for v in st.values())} file(s)/listing(s) failed on the last attempt.")
    if cat:
        g = Counter(d["group"] for d in cat)
        lines.append(f"Catalogue: {len(cat)} datasets ({', '.join(f'{k}: {g[k]}' for k in sorted(g))}), "
                     f"{len(covered)} of them have a manifest source.")
    lines.append("")
    for tier in TIERS:
        rows = [s for s in sources if s.tier == tier]
        if not rows:
            continue
        lines += [f"### Tier {tier}", "", "| id | access | licence | size | feeds | on disk |", "|---|---|---|---:|---|---|"]
        for s in rows:
            have = st.get(s.id)
            if have and have["files"]:
                disk = f"{have['files']} f / {have['bytes'] / 1e6:.1f} MB"
                if have.get("failed"):
                    disk += f", {have['failed']} failed"
            elif have and have.get("failed"):
                disk = f"**{have['failed']} failed**: {have['error'][:60].replace('|', '/')}"
            elif s.fetchable:
                disk = "planned"
            else:
                disk = s.access
            size = f"{s.size_bytes / 1e6:,.0f} MB" if s.size_bytes else "?"
            use = s.harness_use.replace("|", "/")[:110]
            lic = s.license.replace("|", "/")[:28]
            lines.append(f"| `{s.id}` | {s.access} | {lic} | {size} | {use} | {disk} |")
        lines.append("")
    return "\n".join(lines)


def cmd_plan(args) -> int:
    body = render_plan()
    if not args.out:
        print(body)
        return 0
    out = Path(args.out)
    text = out.read_text(encoding="utf-8") if out.exists() else f"# Data plan\n\n{PLAN_BEGIN}\n{PLAN_END}\n"
    if PLAN_BEGIN not in text or PLAN_END not in text:
        text += f"\n{PLAN_BEGIN}\n{PLAN_END}\n"
    head, rest = text.split(PLAN_BEGIN, 1)
    _, tail = rest.split(PLAN_END, 1)
    out.write_text(f"{head}{PLAN_BEGIN}\n\n{body}\n{PLAN_END}{tail}", encoding="utf-8")
    print(f"{out}: plan block refreshed")
    return 0


def cmd_label(args) -> int:
    """Synthetic-degradation labels: one row (params, metrics) per draw, no images stored."""
    from .label import run_label
    s = run_label(args.sources, args.n, out=args.out, per_tile=args.per_tile, crops=args.crops, tile=args.tile,
                  jobs=args.jobs, fmt=args.format, chunk=args.chunk, ss=args.ss, retry_skipped=args.retry_skipped)
    print(f"{s['rows']} rows in {s['out']} ({s['rows_new']} new, {s['chunks_skipped']} chunks skipped), "
          f"{s['rows_per_s_per_proc']:.2f} rows/s per process")
    if s["items_skipped"]:
        print(f"{len(s['items_skipped'])} items skipped (reason x count, recorded in the ledger): "
              + ", ".join(f"{k} x{v}" for k, v in s["skipped"].items()))
    if s["chunks_failed"]:
        print(f"{s['chunks_failed']} chunk(s) FAILED and left for the next run: "
              + "; ".join(f"{f['chunk']} ({f['n_items']} items): {f['error'][:80]}" for f in s["failed"]))
        return 1
    return 0


def cmd_realpairs(args) -> int:
    """Real capture/reference pairs (realpairs.py): build the cached set and its label rows per source, and with
    --compare put the real rows' metric quantiles against the synthetic label rows'."""
    from .realpairs import build_set, compare, compare_markdown, rows_path, set_path, summarise, tile_rows
    rc = 0
    for source in args.sources:
        try:
            rs = build_set(source, args.n, args.tile, args.scale, args.seed, splits=tuple(args.splits), log=print)
        except (ValueError, FileNotFoundError) as ex:
            print(f"{source}: {ex}")
            rc = 1
            continue
        print(summarise(rs))
        path = set_path(source, rs.seed, rs.n, rs.tile, rs.scale)
        print(f"  set: {path}\n  rows: {rows_path(path)}")
        if args.compare:
            from .label import read_labels
            labels = Path(args.labels) if args.labels else data_root() / "labels"
            rep = compare(tile_rows(rs), read_labels(labels))
            md = compare_markdown(rep, f"{source}, seed {rs.seed}, {rs.n} tiles of {rs.tile} px at scale {rs.scale}")
            p = path.with_name(path.stem + "_compare.md")
            p.write_text(md, encoding="utf-8")
            print(md, end="")
            print(f"  report: {p}")
    return rc


def add_parser(sub) -> None:
    d = sub.add_parser("data", help="source registry, collector and derivers")
    ds = d.add_subparsers(dest="dcmd", required=True)

    def common(p):
        p.add_argument("--ids", nargs="*", help="source ids (default: every source within --tier)")
        p.add_argument("--tier", default="S", choices=TIERS, help="largest tier to include (S<50MB, M<2GB, L<50GB)")

    l = ds.add_parser("list", help="sources, tiers, what is already on disk")
    common(l)
    l.add_argument("--access", nargs="*")
    l.set_defaults(func=cmd_list)

    c = ds.add_parser("collect", help="fetch sources (resumable, parallel, ledgered)")
    common(c)
    c.add_argument("--jobs", type=int, default=8)
    c.add_argument("--dry-run", action="store_true")
    c.add_argument("--max-bytes", type=float, help="stop scheduling files past this budget")
    c.add_argument("--param", action="append", metavar="K=V", help="override an expander param, e.g. resolution=4k limit=50")
    c.set_defaults(func=cmd_collect)

    s = ds.add_parser("status", help="ledger summary")
    s.set_defaults(func=cmd_status)

    v = ds.add_parser("derive", help="build harness-ready tables under data/derived")
    v.add_argument("--ids", nargs="*")
    v.set_defaults(func=cmd_derive)

    pl = ds.add_parser("plan", help="render the source/status table (stdout, or refresh the block in --out)")
    pl.add_argument("--out", help="markdown file holding the plan:begin/plan:end block, e.g. DATA_PLAN.md")
    pl.set_defaults(func=cmd_plan)

    lb = ds.add_parser("label", help="label synthetic degradations of clean tiles (params + metrics per draw)")
    lb.add_argument("--sources", nargs="+", required=True, help="source ids under <data root>/raw")
    lb.add_argument("--n", type=int, required=True, help="approximate number of rows to produce")
    lb.add_argument("--out", help="shard directory (default <data root>/labels)")
    lb.add_argument("--per-tile", type=int, default=4, help="parameter draws per clean tile")
    lb.add_argument("--crops", type=int, default=4, help="random tiles per clean image")
    lb.add_argument("--tile", type=int, default=256, help="tile side in pixels")
    lb.add_argument("--jobs", type=int, default=None, help="worker processes (default: all cores)")
    lb.add_argument("--format", choices=("parquet", "jsonl"), default="parquet")
    lb.add_argument("--chunk", type=int, default=8, help="clean images per shard")
    lb.add_argument("--ss", type=int, default=1, help="camera-model supersampling factor")
    lb.add_argument("--retry-skipped", action="store_true",
                    help="label again the items the ledger records as skipped (unreadable or too small)")
    lb.set_defaults(func=cmd_label)

    rp = ds.add_parser("realpairs", help="real capture/reference pairs: aligned, gain-matched tiles with label rows")
    rp.add_argument("--sources", nargs="+", default=["rawnind", "hdr-plus-burst"], help="rawnind and/or hdr-plus-burst")
    rp.add_argument("--n", type=int, default=64, help="tiles in the set (a function of source, seed, n, tile, scale)")
    rp.add_argument("--tile", type=int, default=256)
    rp.add_argument("--scale", type=int, help="working scale (default: the manifest's clean scale)")
    rp.add_argument("--seed", type=int, default=0)
    rp.add_argument("--splits", nargs="+", default=["val", "test"], help="scene splits the pairs come from")
    rp.add_argument("--compare", action="store_true", help="real rows' metric quantiles against the synthetic label rows'")
    rp.add_argument("--labels", help="synthetic label shard directory for --compare (default <data root>/labels)")
    rp.set_defaults(func=cmd_realpairs)
